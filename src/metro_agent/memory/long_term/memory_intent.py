"""
长期记忆系统 — 意图识别模块
===========================
负责判断用户输入是否属于「记忆查询」以及识别记忆类别。

两条主要功能：
  1. detect_memory_category — 关键词匹配检测记忆类别
  2. is_memory_query — 判断用户是否在查询/查看自己的记忆

区分记忆查询和普通对话的意义：
  - 记忆查询（is_memory_query=True）→ 路由到 memory_recall_node，直接返回记忆内容
  - 普通对话 → 走正常的 Agent 流程，对话结束后由 curator 提取新记忆
"""

# ============================================================
# 记忆类别 → 触发关键词映射
# 用于从用户输入中检测记忆类别
# ============================================================
MEMORY_TOPICS = {
    "plan": ("计划", "安排", "打算"),
    "goal": ("目标", "目的"),
    "preference": ("偏好", "喜欢", "习惯"),
    "identity": ("身份", "个人信息"),
    "requirement": ("要求", "需求"),
}

# ============================================================
# 直接召回模式
# 用户明确要求查看记忆，匹配任一即视为记忆查询
# ============================================================
DIRECT_RECALL_PATTERNS = (
    "你记得我",
    "你记得关于我",
    "你记住了什么",
    "查看我的记忆",
    "列出我的记忆",
    "我是谁",
    "我的长期记忆",
)

# ============================================================
# 助手记忆动词
# 用户询问助手存储了什么，配合"记忆"和疑问标记使用
# ============================================================
ASSISTANT_MEMORY_VERBS = (
    "你记得",
    "你记住",
    "你保存",
    "你存了",
    "你存有",
    "你目前存",
    "你当前存",
    "你存在哪些",
)

# ============================================================
# 疑问标记
# 用于判断用户是否在提问（配合类别和"我"字判断记忆查询）
# ============================================================
QUERY_MARKERS = (
    "什么", "哪些", "有没有",
    "多少", "查看", "列出",
    "吗", "?", "？",
)


# ============================================================
# 记忆类别检测
# ============================================================

def detect_memory_category(text: str) -> str | None:
    """检测用户输入文本所属的记忆类别。

    遍历 MEMORY_TOPICS 中定义的所有类别，使用简单的子串匹配。
    如果用户输入包含某个类别的任一关键词，返回该类别的标识符。

    Args:
        text: 用户输入的原始文本。

    Returns:
        匹配到的记忆类别字符串（"plan"/"goal"/"preference"/"identity"/"requirement"），
        未匹配到任何类别时返回 None。
    """
    for category, keywords in MEMORY_TOPICS.items():
        if any(word in text for word in keywords):
            return category
    return None


# ============================================================
# 记忆查询判断
# ============================================================

def is_memory_query(text: str) -> bool:
    """判断用户输入是否为记忆查询。

    三级判断逻辑（满足任一即返回 True）：

      第一级 — 直接召回模式匹配：
        用户明确说"你记得我"、"查看我的记忆"等，直接判定为记忆查询。

      第二级 — 个人记忆查询：
        同时满足三个条件：
          1. 包含某个记忆类别的关键词（如"偏好"、"计划"）
          2. 包含"我"字（表示查询自己的记忆）
          3. 包含疑问标记（如"吗"、"哪些"、"？"）
        例："你有什么偏好？" → True

      第三级 — 助手记忆查询：
        同时满足三个条件：
          1. 包含"记忆"一词
          2. 包含疑问标记
          3. 包含助手记忆动词（如"你记得"、"你存了"）
        例："你还存了什么记忆？" → True

    Args:
        text: 用户输入的原始文本。

    Returns:
        True 表示用户正在查询记忆，应路由到 memory_recall_node；
        False 表示普通对话，走正常 Agent 流程。
    """
    text = text.strip()

    # 第一级：直接召回模式
    if any(p in text for p in DIRECT_RECALL_PATTERNS):
        return True

    # 辅助判断：是否包含疑问标记
    asks = any(word in text for word in QUERY_MARKERS)
    category = detect_memory_category(text)

    # 第二级：有关"我"的某类别记忆查询
    if category and "我" in text and asks:
        return True

    # 第三级：询问助手存储了什么记忆
    asks_about_stored_memory = (
        "记忆" in text
        and asks
        and any(v in text for v in ASSISTANT_MEMORY_VERBS)
    )

    return asks_about_stored_memory